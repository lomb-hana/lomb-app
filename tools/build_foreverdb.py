#!/usr/bin/env python3
"""Build the bundled ForeverDB.net data files (LOMBCompanion/Data/ForeverDB/*.lua).

Offline step, run by a maintainer -- the addon itself never goes online.

    FOREVERDB_API_KEY=... python3 tools/fdb_pull_all.py      # polite, cached, sequential
    python3 tools/build_foreverdb.py                          # reads the cache only

The API key is read from the environment by tools/fdb_fetch.py and is never
written anywhere. This script makes no network requests at all.

Scope: levels 1-30 (WoW: Forever's level cap). Quests, quest givers/hand-ins,
vendors seen in WoW Forever, profession recipes up to skill 225 (Expert, the
most a level-30 character can train), dungeons up to the mid-30s, and the items
those reference. Mob loot tables are NOT included (the guild records its own).

Classic data: ForeverDB marks facts that come from Classic (CMaNGOS) rather than
from what players saw in WoW Forever. Vendors and trainers that were never seen
in Forever are left out. Quests are all in the Forever client, so they're kept,
but any giver, hand-in, location or chain link that comes from Classic data keeps
a "Classic data" flag (c = 1), and the addon labels it "(Classic data, may differ)".
"""
import datetime
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from fdb_fetch import get  # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "LOMBCompanion", "Data", "ForeverDB")
MAX_LEVEL = 30
MAX_SKILL = 225
MAX_DUNGEON_MIN_LEVEL = 35
SNAPSHOT = os.environ.get("FDB_SNAPSHOT_DATE") or datetime.date.today().isoformat()

HEADER = (
    "-- Data from ForeverDB.net (https://foreverdb.net), used with permission. "
    "Not covered by this project's MIT license.\n"
    "-- Snapshot: {date} (WoW: Forever build {build}). Generated by tools/build_foreverdb.py -- do not edit by hand.\n"
)


def C(obj):
    return get(*obj, cache_only=True) if isinstance(obj, tuple) else get(obj, cache_only=True)


def pages(path, params=None, stop=None):
    out, off = [], 0
    while True:
        p = dict(params or {}, limit=100, offset=off)
        r = get(path, p, cache_only=True)
        data = r["data"]
        rows = data if isinstance(data, list) else data.get("recipes") or []
        out.append(r)
        nxt = (r.get("meta") or {}).get("next")
        if not rows or nxt is None:
            break
        if stop and stop(r):
            break
        off += 100
    return out


# ---------------------------------------------------------------- Lua output
def lua(v, ind=""):
    if v is None:
        return "nil"
    if v is True:
        return "true"
    if v is False:
        return "false"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, float):
        s = ("%.1f" % v)
        return s[:-2] if s.endswith(".0") else s
    if isinstance(v, str):
        return '"' + v.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("|", "||") + '"'
    if isinstance(v, (list, tuple)):
        # trailing nils can't sit in a Lua array literal; strip them
        v = list(v)
        while v and v[-1] is None:
            v.pop()
        return "{" + ",".join(lua(x) for x in v) + "}"
    if isinstance(v, dict):
        parts = []
        for k, x in v.items():
            if x is None:
                continue
            if isinstance(k, int):
                parts.append("[%d]=%s" % (k, lua(x)))
            elif re.match(r"^[A-Za-z_][A-Za-z0-9_]*$", k):
                parts.append("%s=%s" % (k, lua(x)))
            else:
                parts.append("[%s]=%s" % (lua(k), lua(x)))
        return "{" + ",".join(parts) + "}"
    raise TypeError(type(v))


def write(name, build, body_lines, what):
    path = os.path.join(OUT, name)
    with open(path, "w", newline="\n") as f:
        f.write(HEADER.format(date=SNAPSHOT, build=build))
        f.write("-- %s\n" % what)
        f.write("local _, ns = ...\n")
        f.write("local D = ns.FDBData\n")
        for line in body_lines:
            f.write(line + "\n")
    return os.path.getsize(path)


def is_classic(src):
    return bool(src) and "classic" in src.lower()


def side(s):
    return {"a": "A", "h": "H", "both": "B", "Alliance": "A", "Horde": "H", "Both": "B"}.get(s, "B")


def coord(v):
    return round(v, 1) if isinstance(v, (int, float)) else None


# ---------------------------------------------------------------- build
def main():
    os.makedirs(OUT, exist_ok=True)
    meta = C("meta")["data"]
    build = meta.get("build", "?")
    items = {}       # itemId -> [name, quality]
    QUAL = {"poor": 0, "common": 1, "uncommon": 2, "rare": 3, "epic": 4, "legendary": 5}

    def item(iid, name, q=None):
        if not iid:
            return
        e = items.get(iid)
        if not e:
            items[iid] = [name, QUAL.get((q or "").lower()) if isinstance(q, str) else q]
        else:
            if e[0] is None and name:
                e[0] = name
            if e[1] is None and q is not None:
                e[1] = QUAL.get(q.lower()) if isinstance(q, str) else q

    # ---- quests
    quests = {}
    for r in pages("quests", {"maxLevel": MAX_LEVEL}):
        for q in r["data"]:
            if not q.get("knownInForever"):
                continue
            def ep(e):
                if not e or not e.get("type"):
                    return None
                loc = e.get("location") or {}
                t = {"npc": "n", "object": "o", "item": "i"}.get(e["type"], "n")
                if t == "i":
                    item(e.get("id"), e.get("name"))
                return [t, e.get("id") or 0, e.get("name") or "?", loc.get("zone"), coord(loc.get("x")), coord(loc.get("y")),
                        1 if (is_classic(e.get("source")) or is_classic(loc.get("source"))) else 0]
            ch = q.get("chain") or {}
            rec = {
                "n": q["name"], "l": q.get("level") or 0, "r": q.get("requiredLevel") or 0,
                "s": side(q.get("side")),
                "z": (q.get("zone") or {}).get("n") or q.get("category") or None,
                "st": ep(q.get("starts")), "en": ep(q.get("ends")),
                "pv": [c["questId"] for c in ch.get("previous") or [] if c.get("questId")] or None,
                "nx": [c["questId"] for c in ch.get("next") or [] if c.get("questId")] or None,
                "c": 1 if q.get("source") == "classic" else None,
            }
            ql = ch.get("questLine")
            if isinstance(ql, dict) and ql.get("name"):
                rec["ql"] = ql["name"]
            elif isinstance(ql, str):
                rec["ql"] = ql
            quests[q["id"]] = rec

    # ---- vendors (seen in WoW Forever only)
    vlist = []
    for r in pages("vendors"):
        vlist += r["data"]
    vendors = {}
    for v in vlist:
        if not v.get("seenInForever"):
            continue
        try:
            d = get("vendors/%d" % v["id"], cache_only=True)["data"]
        except Exception:
            d = {}
        sells = []
        for s in d.get("sells") or []:
            item(s.get("itemId"), s.get("name"), s.get("quality"))
            sells += [s.get("itemId"), s.get("price") or 0, s.get("stack") or 1, 1 if s.get("limited") else 0]
        rf = v.get("reputationFaction")
        vendors[v["id"]] = {
            "n": v["name"], "t": v.get("title") or None, "s": side(v.get("side")),
            "z": (v.get("zone") if isinstance(v.get("zone"), str) else (v.get("zone") or {}).get("n")),
            "x": coord(v.get("x")), "y": coord(v.get("y")),
            "rf": rf.get("name") if isinstance(rf, dict) else rf,
            "i": sells or None,
        }

    # ---- professions + recipes (skill <= 225)
    profs = {}
    plist = C("professions")["data"]
    for p in plist:
        slug = p["slug"]
        reqs = pages("professions/" + slug,
                     stop=lambda r: min([x["skill"]["orange"] or 0 for x in r["data"]["recipes"]] or [0]) > MAX_SKILL)
        first = reqs[0]["data"]
        trainers = []
        for t in first.get("trainers") or []:
            if not t.get("seenInForever"):
                continue
            trainers.append({"id": t["npcId"], "n": t["name"], "t": t.get("title"), "s": side(t.get("side")),
                             "z": t.get("zone"), "x": coord(t.get("x")), "y": coord(t.get("y")),
                             "up": t.get("trainsUpToSkill")})
        recipes = []
        for r in reqs:
            for x in r["data"]["recipes"]:
                sk = x.get("skill") or {}
                if (sk.get("orange") or 0) > MAX_SKILL:
                    continue
                lf = x.get("learnedFrom") or {}
                src = lf.get("sources") or {}
                ways = list(src.get("ways") or [])
                if lf.get("automatic") and "auto" not in ways:
                    ways.insert(0, "auto")
                mk = x.get("makes") or {}
                item(mk.get("itemId"), mk.get("name"), mk.get("quality"))
                rg = []
                for g in x.get("reagents") or []:
                    item(g.get("itemId"), g.get("name"))
                    rg += [g.get("itemId"), g.get("count") or 1]
                ri = src.get("recipeItem") or {}
                item(ri.get("itemId"), ri.get("name"))
                # vendors/trainers: only ones seen in WoW Forever
                sv = set()
                for fac in (src.get("vendors") or {}).values():
                    for v in fac or []:
                        if v.get("seenInForever"):
                            sv.add(v["npcId"])
                st = set(t.get("npcId") for t in lf.get("seenAtForeverTrainers") or [] if isinstance(t, dict) and t.get("npcId"))
                for fac in (src.get("trainers") or {}).values():
                    for t in fac or []:
                        if t.get("seenInForever"):
                            st.add(t["npcId"])
                cost = src.get("trainerCost") if not is_classic(src.get("trainerCostSource")) else None
                recipes.append({
                    "sp": x.get("spellId"), "n": x["name"], "cat": (x.get("category") or {}).get("name"),
                    "sk": [sk.get("orange"), sk.get("yellow"), sk.get("green"), sk.get("grey")],
                    "rl": x.get("requiredLevel") or None,
                    "mk": mk.get("itemId"), "mc": (mk.get("count") or 1) if mk.get("itemId") else None,
                    "rg": rg or None,
                    "w": ",".join(ways) or None, "ri": ri.get("itemId"),
                    "vs": sorted(sv) or None, "ts": sorted(st) or None, "tc": cost,
                    "new": 1 if x.get("newInForever") else None,
                })
        profs[slug] = {"n": p["name"], "k": p.get("kind"),
                       "ranks": [[k.get("rank"), k.get("maxSkill")] for k in first.get("ranks") or []] or None,
                       "tr": trainers or None, "r": recipes}

    # ---- dungeons
    dungeons = {}
    for d in C(("dungeons", {"limit": 100, "offset": 0}))["data"]:
        det = get("dungeons/%d" % d["id"], cache_only=True)["data"]
        lr = det.get("levelRange")
        if not det.get("newInForever") and (not lr or lr[0] > MAX_DUNGEON_MIN_LEVEL):
            continue
        loot = []
        for n in det.get("notableLoot") or []:
            item(n.get("itemId"), n.get("name"))
            loot.append([n.get("itemId"), "; ".join(n.get("why") or [])])
        dungeons[d["id"]] = {"n": det["name"], "k": det.get("kind"), "p": det.get("players"),
                             "lv": det.get("level"), "lr": lr, "st": det.get("status"),
                             "new": 1 if det.get("newInForever") else None,
                             "b": det.get("bosses") or None, "lo": loot or None}

    # ---- item details (quality, required level, slot) from the items list (required level <= 30).
    # Only for items the files above mention -- the full list is far too big to bundle.
    meta_by_id = {}
    off = 0
    while True:
        try:
            r = get("items", {"maxLevel": MAX_LEVEL, "limit": 100, "offset": off}, cache_only=True)
        except Exception:
            print("note: items list not fully cached (stopped at offset %d)" % off, file=sys.stderr)
            break
        for it in r.get("data") or []:
            meta_by_id[it["id"]] = it
        if not r.get("data") or (r.get("meta") or {}).get("next") is None:
            break
        off += 100
    for iid, e in items.items():
        it = meta_by_id.get(iid)
        if not it:
            continue
        if not e[0]:
            e[0] = it.get("name")
        if e[1] is None and it.get("qualityId") is not None:
            e[1] = it["qualityId"]
        inv, cls, sub = it.get("inventoryType"), it.get("class"), it.get("subclass")
        if inv and inv != "Non-equippable":
            slot = inv + (" " + sub if cls in ("Weapon", "Armor") and sub and sub not in ("Miscellaneous", inv) else "")
        else:
            slot = sub if sub and sub not in ("Other", "Junk") else cls
        e[:] = (e + [None, None])[:2] + [it.get("requiredLevel") or 0, slot or None]
    for iid in [k for k, e in items.items() if not e[0]]:
        del items[iid]   # nothing to show without a name
    for e in items.values():
        while e and e[-1] is None:
            e.pop()

    # ---- write
    sizes = {}
    # Core.lua creates ns.FDBData; it loads first (see the .toc).
    with open(os.path.join(OUT, "Core.lua"), "w", newline="\n") as f:
        f.write(HEADER.format(date=SNAPSHOT, build=build))
        f.write("-- Snapshot info; the other files in this folder fill in ns.FDBData.\n")
        f.write("local _, ns = ...\n")
        f.write("ns.FDBData = { snapshot = %s, build = %s, quests = {}, vendors = {}, professions = {}, dungeons = {}, items = {} }\n"
                % (lua(SNAPSHOT), lua(build)))
    sizes["Core.lua"] = os.path.getsize(os.path.join(OUT, "Core.lua"))

    def body(var, mapping):
        lines = []
        for k in sorted(mapping):
            lines.append("D.%s[%s]=%s" % (var, k if isinstance(k, int) else lua(k), lua(mapping[k])))
        return lines

    sizes["Quests.lua"] = write("Quests.lua", build, body("quests", quests),
                                "Quests up to level %d: [questID] = { n=name, l=level, r=required level, s=side A/H/B, z=zone, "
                                "st/en={type n/o/i, id, name, zone, x, y, classic}, pv/nx=chain, c=1 Classic-sourced }" % MAX_LEVEL)
    sizes["Vendors.lua"] = write("Vendors.lua", build, body("vendors", vendors),
                                 "Vendors seen in WoW Forever: [npcID] = { n, t=title, s=side, z=zone, x, y, rf=reputation, "
                                 "i={itemID, price (copper), stack, limited, ...} }")
    sizes["Recipes.lua"] = write("Recipes.lua", build, body("professions", profs),
                                 "Professions, recipes up to skill %d: r={ sp=spell, n, cat, sk={orange,yellow,green,grey}, "
                                 "mk=item made, mc=count, rg={itemID,count,...}, w=ways learned, ri=recipe item, "
                                 "vs/ts=vendors/trainers seen in Forever, tc=trainer cost }" % MAX_SKILL)
    sizes["Dungeons.lua"] = write("Dungeons.lua", build, body("dungeons", dungeons),
                                  "Dungeons: [id] = { n, k=kind, p=players, lv, lr={min,max}, st=status, b=bosses, "
                                  "lo={{itemID, why}} notable loot (not drop tables) }")
    sizes["Items.lua"] = write("Items.lua", build, body("items", {k: v for k, v in items.items() if k}),
                               "Items the other files mention: [itemID] = { name, quality, required level, slot/type }")
    total = sum(sizes.values())
    print(json.dumps({"quests": len(quests), "vendors": len(vendors),
                      "recipes": sum(len(p["r"]) for p in profs.values()), "professions": len(profs),
                      "dungeons": len(dungeons), "items": len(items), "bytes": sizes, "total_kb": round(total / 1024, 1)},
                     indent=1))


if __name__ == "__main__":
    main()
