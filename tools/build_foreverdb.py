#!/usr/bin/env python3
"""Build the bundled ForeverDB.net data files (LOMBCompanion/Data/ForeverDB/*.lua).

Offline step, run by a maintainer -- the addon itself never goes online.

    FOREVERDB_API_KEY=... python3 tools/fdb_pull_all.py      # polite, cached, sequential
    python3 tools/build_foreverdb.py                          # reads the cache only

The API key is read from the environment by tools/fdb_fetch.py and is never
written anywhere. This script makes no network requests at all.

Scope: levels 1-30 (WoW: Forever's level cap). Quests, quest givers/hand-ins,
vendors seen in WoW Forever, profession recipes up to skill 225 (Expert, the
most a level-30 character can train), dungeons up to the mid-30s, and the items
those reference. Mob loot tables are NOT included (the guild records its own).

Classic data: ForeverDB marks facts that come from Classic (CMaNGOS) rather than
from what players saw in WoW Forever. Vendors and trainers that were never seen
in Forever are left out. Quests are all in the Forever client, so they're kept,
but any giver, hand-in, location or chain link that comes from Classic data keeps
a "Classic data" flag (c = 1), and the addon labels it "(Classic data, may differ)".
"""
import datetime
