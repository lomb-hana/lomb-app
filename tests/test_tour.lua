local H = dofile((arg[0]:match("^(.*)/[^/]+$") or ".") .. "/harness.lua")

print("Welcome tour")

H.test("shows once on the first window open; skip remembers", function()
  local ns = H.boot()
  H.eq(ns.db.settings.tourDone, false)
  ns.UI.Open()
  H.advance(0.2)
  H.ok(ns.Tour.IsShown(), "tour on first open")
  H.eq(ns.Tour.i, 1)
  H.ok(ns.Tour.frame.title:GetText():find("Welcome"))
  H.ok(not ns.Tour.frame.back:IsShown(), "no Back on step 1")
  ns.Tour.frame.skip:Click()
  H.ok(not ns.Tour.IsShown(), "skipped")
  H.eq(ns.db.settings.tourDone, true)
  ns.UI.frame:Hide(); ns.UI.Open(); H.advance(0.2)
  H.ok(not ns.Tour.IsShown(), "not shown again")
  H.noErrors("tour")
end)

H.test("next / back walk the steps; the sharing step opens Settings; Done closes", function()
  local ns = H.boot()
  ns.UI.Open(); H.advance(0.2)
  local f = ns.Tour.frame
  f.next:Click(); H.eq(ns.Tour.i, 2); H.ok(f.hl:IsShown(), "outline shown")
  f.back:Click(); H.eq(ns.Tour.i, 1)
  f.next:Click(); f.next:Click()
  H.eq(ns.Tour.i, 3); H.eq(ns.UI.current, "settings", "sharing step opens Settings")
  f.next:Click()
  H.eq(ns.Tour.i, #ns.Tour.STEPS)
  H.ok(f.body:GetText():find("/lomb test", 1, true))
  H.eq(f.next.label:GetText(), "Done")
  H.ok(not f.skip:IsShown())
  f.next:Click()
  H.ok(not ns.Tour.IsShown(), "done")
  H.eq(ns.db.settings.tourDone, true)
end)

H.test("closing the window (ESC) mid-tour counts as seen; reopen from Settings and /lomb tour", function()
  local ns = H.boot()
  ns.UI.Open(); H.advance(0.2)
  ns.UI.frame:Hide()
  H.eq(ns.db.settings.tourDone, true, "ESC closes the window and the tour")
  ns.HandleSlash("tour")
  H.ok(ns.Tour.IsShown(), "/lomb tour")
  H.eq(ns.Tour.i, 1)
  ns.Tour.Stop()
  ns.UI.Open("settings")
  H.noErrors("reopen")
end)

H.test("upgrading players see it once too; old saved settings get the flag", function()
  local ns = H.boot()
  ns.db.settings.tourDone = nil
  local ns2 = H.boot({ db = _G.LOMBCompanionDB, charDB = _G.LOMBCompanionCharDB })
  H.eq(ns2.db.settings.tourDone, false)
end)

H.done()
